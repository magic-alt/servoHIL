def remove_old_status(text):
    items=list(expressions(text));out=[];i=0;found=False
    while i<len(items):
        item=items[i]
        if item.startswith('(symbol ') and '(property "Reference" "U409"' in item:
            found=True;i+=1
            while i<len(items) and items[i].startswith(('(wire ','(global_label ','(no_connect ')):i+=1
            continue
        out.append(item);i+=1
    if not found:raise ValueError('U409 removal target missing')
    return '(kicad_sch\n'+'\n'.join(out)+'\n)\n'


def graphics(text):
    def line(points):
        return '(polyline (pts '+''.join(f'(xy {x} {y})' for x,y in points)+') (stroke (width 0.254) (type default)) (fill (type none)))'
    shapes={
      'D':line([(-2.54,-2.54),(-2.54,2.54)])+' '+line([(-2.54,0),(2.54,2.54),(2.54,-2.54),(-2.54,0)]),
      'F':'(rectangle (start -2.54 1.27) (end 2.54 -1.27) (stroke (width 0.254) (type default)) (fill (type none))) '+line([(-2.54,0),(2.54,0)]),
      'SW':line([(-2.54,0),(1.905,2.54)])+' (circle (center -2.54 0) (radius 0.508) (stroke (width 0.254) (type default)) (fill (type none))) (circle (center 2.54 0) (radius 0.508) (stroke (width 0.254) (type default)) (fill (type none)))',
      'TESTPOINT':'(circle (center 0 0) (radius 2.54) (stroke (width 0.254) (type default)) (fill (type none)))',
    }
    shapes['L']=' '.join(f'(arc (start {a} 0) (mid {a+0.635} 0.635) (end {a+1.27} 0) (stroke (width 0.254) (type default)) (fill (type none)))' for a in [-2.54,-1.27,0,1.27])
    for name,shape in shapes.items():
        marker='(symbol "'+name+'_0_1"'
        if marker in text:
            a,b,_=block(text,marker);text=text[:a]+marker+' '+shape+')'+text[b:]
    return text



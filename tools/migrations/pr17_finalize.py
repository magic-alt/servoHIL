def replace_once(text,old,new):
    if text.count(old)!=1:raise ValueError('unexpected edit context: '+old[:100])
    return text.replace(old,new,1)


def block(text,marker,offset=0):
    start=text.index(marker,offset);depth=0;quoted=escaped=False
    for i in range(start,len(text)):
        c=text[i]
        if quoted:
            if escaped:escaped=False
            elif c=='\\':escaped=True
            elif c=='"':quoted=False
        elif c=='"':quoted=True
        elif c=='(':depth+=1
        elif c==')':
            depth-=1
            if depth==0:return start,i+1,text[start:i+1]
    raise ValueError('unbalanced expression')


def modify_ldo(text,name):
    marker='(symbol "'+name+'"'
    if marker not in text:return text
    start,end,root=block(text,marker);hits=[]
    for m in re.finditer(r'\(pin power_out line',root):
        a,b,pin=block(root,'(pin power_out line',m.start())
        if '(number "12"' in pin:hits.append((a,b,pin))
    if len(hits)!=1:raise ValueError('expected one internally duplicated OUT12 in '+name)
    a,b,pin=hits[0]
    root=root[:a]+pin.replace('(pin power_out','(pin passive',1)+root[b:]
    return text[:start]+root+text[end:]


